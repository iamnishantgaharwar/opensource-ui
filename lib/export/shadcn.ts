import { cssGroups, type ExportFile } from "@/lib/export/shared"
import type { TokenGroup } from "@/lib/tokens/types"

const THEME_NAMESPACE = { color: "color" } as const

// shadcn's radius setup. No module generates radius yet, but replacing the
// :root and @theme inline blocks would otherwise drop it and break rounded-*.
const RADIUS_ROOT = "  --radius: 0.625rem;"
const RADIUS_THEME = [
  "  --radius-sm: calc(var(--radius) * 0.6);",
  "  --radius-md: calc(var(--radius) * 0.8);",
  "  --radius-lg: var(--radius);",
  "  --radius-xl: calc(var(--radius) * 1.4);",
  "  --radius-2xl: calc(var(--radius) * 1.8);",
  "  --radius-3xl: calc(var(--radius) * 2.2);",
  "  --radius-4xl: calc(var(--radius) * 2.6);",
]

/**
 * shadcn / Tailwind v4 globals.css: `:root` and `.dark` variable blocks plus
 * a complete `@theme inline` block mapping every color (shadcn's own and the
 * extras like `bg-primary-500`, `text-link`) to Tailwind utilities. Each block
 * can replace the user's block of the same name as a whole.
 */
export function exportShadcn(tree: TokenGroup): ExportFile {
  const root: string[] = ["  /* Radius (shadcn default) */", RADIUS_ROOT]
  const dark: string[] = []
  const theme: string[] = []

  for (const { label, leaves } of cssGroups(tree)) {
    root.push(`  /* ${label} */`)
    for (const { token } of leaves) {
      root.push(`  --${token.$css}: ${token.$value};`)
    }

    const darkLeaves = leaves.filter((l) => l.token.$dark !== undefined)
    if (darkLeaves.length) {
      dark.push(`  /* ${label} */`)
      for (const { token } of darkLeaves) {
        dark.push(`  --${token.$css}: ${token.$dark};`)
      }
    }

    const themeLines = leaves.flatMap(({ token }) => {
      const ns = THEME_NAMESPACE[token.$type as keyof typeof THEME_NAMESPACE]
      return ns ? [`  --${ns}-${token.$css}: var(--${token.$css});`] : []
    })
    if (themeLines.length) theme.push(`  /* ${label} */`, ...themeLines)
  }

  const code = [
    "/*",
    " * Generated by opensource-ui.",
    " * In your globals.css, replace the :root, .dark and @theme inline blocks",
    " * with these. Keep your @import, @custom-variant and @layer base lines,",
    " * and copy any --font-* lines from your old @theme inline block into this one.",
    " */",
    "",
    ":root {",
    ...root,
    "}",
    "",
    ".dark {",
    ...dark,
    "}",
    "",
    "@theme inline {",
    ...theme,
    "  /* Radius */",
    ...RADIUS_THEME,
    "}",
    "",
  ].join("\n")

  return { filename: "globals.css", language: "css", code }
}
