import { cssGroups, hslChannels, type ExportFile } from "@/lib/export/shared"
import { stylesheetImports } from "@/lib/tokens/css"
import type { Token, TokenGroup } from "@/lib/tokens/types"

type ColorTree = Record<string, Record<string, string>>
type FontSizeOptions = Record<string, string>
type FontSizes = Record<string, [string, FontSizeOptions]>

// Tailwind v3's default spacing keys; with a `spacing` variable each becomes
// calc(var(--spacing) * n), as Tailwind v4 does natively.
const V3_SPACING_KEYS = [
  0, 0.5, 1, 1.5, 2, 2.5, 3, 3.5, 4, 5, 6, 7, 8, 9, 10, 11, 12, 14, 16, 20, 24,
  28, 32, 36, 40, 44, 48, 52, 56, 60, 64, 72, 80, 96,
]

// `text-h1--line-height` → the v3 fontSize option it becomes.
const SIZE_OPTIONS: Record<string, string> = {
  "line-height": "lineHeight",
  "letter-spacing": "letterSpacing",
  "font-weight": "fontWeight",
}

/**
 * Reads a token's Tailwind theme names into v3 config entries: `font-x` →
 * fontFamily.x, `radius-x` → borderRadius.x, `shadow-x` → boxShadow.x,
 * `text-x` → fontSize.x,
 * `text-x--line-height` etc. → that size's options.
 */
function collectTheme(
  token: Token,
  fontFamily: Record<string, string>,
  borderRadius: Record<string, string>,
  boxShadow: Record<string, string>,
  fontSize: FontSizes,
  spacing: { ref?: string }
) {
  const ref = `var(--${token.$css})`
  for (const name of token.$theme ?? []) {
    const [base, option] = name.split("--")
    if (base === "spacing" && !option) {
      spacing.ref = ref
    } else if (base.startsWith("radius-") && !option) {
      borderRadius[base.slice(7)] = ref
    } else if (base.startsWith("shadow-") && !option) {
      boxShadow[base.slice(7)] = ref
    } else if (base.startsWith("font-") && !option) {
      fontFamily[base.slice(5)] = ref
    } else if (base.startsWith("text-")) {
      const key = base.slice(5)
      fontSize[key] ??= ["", {}]
      if (!option) fontSize[key][0] = ref
      else if (SIZE_OPTIONS[option])
        fontSize[key][1][SIZE_OPTIONS[option]] = ref
    }
  }
}

/**
 * Tailwind v3 in shadcn's v3 style: HSL channel variables in globals.css and
 * a config that wraps them in `hsl(var(--x))`. Names split on the first dash:
 * `primary-500` → colors.primary.500, `primary` → colors.primary.DEFAULT.
 * Other tokens (fonts, sizes, radius) are plain variables, wired into
 * fontFamily, fontSize and borderRadius.
 */
export function exportTailwindV3(tree: TokenGroup): ExportFile[] {
  const root: string[] = []
  const dark: string[] = []
  const colors: ColorTree = {}
  const fontFamily: Record<string, string> = {}
  const borderRadius: Record<string, string> = {}
  const boxShadow: Record<string, string> = {}
  const fontSize: FontSizes = {}
  const spacing: { ref?: string } = {}

  for (const { label, leaves } of cssGroups(tree)) {
    const colorLeaves = leaves.filter((l) => l.token.$type === "color")
    if (!colorLeaves.length) {
      root.push(`    /* ${label} */`)
      const darkLines: string[] = []
      for (const { token } of leaves) {
        root.push(`    --${token.$css}: ${token.$value};`)
        if (token.$dark !== undefined) {
          darkLines.push(`    --${token.$css}: ${token.$dark};`)
        }
        collectTheme(
          token,
          fontFamily,
          borderRadius,
          boxShadow,
          fontSize,
          spacing
        )
      }
      if (darkLines.length) dark.push(`    /* ${label} */`, ...darkLines)
      continue
    }
    root.push(`    /* ${label} */`)
    const darkLines: string[] = []
    for (const { token } of colorLeaves) {
      const name = token.$css!
      root.push(`    --${name}: ${hslChannels(String(token.$value))};`)
      if (token.$dark !== undefined) {
        darkLines.push(`    --${name}: ${hslChannels(String(token.$dark))};`)
      }
      const [group, ...rest] = name.split("-")
      colors[group] ??= {}
      colors[group][rest.length ? rest.join("-") : "DEFAULT"] =
        `hsl(var(--${name}))`
    }
    if (darkLines.length) dark.push(`    /* ${label} */`, ...darkLines)
  }

  const imports = stylesheetImports(tree)
  const css = [
    "/* Generated by csskit. Replace your :root and .dark blocks. */",
    ...imports.map(
      (url) => `/* Fonts: add as the first line: @import url("${url}"); */`
    ),
    "@layer base {",
    "  :root {",
    ...root,
    "  }",
    "",
    "  .dark {",
    ...dark,
    "  }",
    "}",
    "",
  ].join("\n")

  const config = [
    "/** @type {import('tailwindcss').Config} */",
    "module.exports = {",
    '  darkMode: ["class"],',
    "  theme: {",
    "    extend: {",
    `      colors: ${formatColors(colors, 6)},`,
    ...(Object.keys(fontFamily).length
      ? [`      fontFamily: ${formatFontFamily(fontFamily, 6)},`]
      : []),
    ...(Object.keys(fontSize).length
      ? [`      fontSize: ${formatFontSize(fontSize, 6)},`]
      : []),
    ...(Object.keys(borderRadius).length
      ? [`      borderRadius: ${formatStrings(borderRadius, 6)},`]
      : []),
    ...(Object.keys(boxShadow).length
      ? [`      boxShadow: ${formatStrings(boxShadow, 6)},`]
      : []),
    ...(spacing.ref
      ? [
          `      spacing: Object.fromEntries(`,
          `        [${V3_SPACING_KEYS.join(", ")}].map(`,
          `          (n) => [n, \`calc(${spacing.ref} * \${n})\`]`,
          `        )`,
          `      ),`,
        ]
      : []),
    "    },",
    "  },",
    "}",
    "",
  ].join("\n")

  return [
    { filename: "globals.css", language: "css", code: css },
    { filename: "tailwind.config.js", language: "js", code: config },
  ]
}

const key = (k: string) =>
  /^([a-z_]\w*|\d+)$/i.test(k) ? k : JSON.stringify(k)

function formatColors(colors: ColorTree, indent: number) {
  const pad = " ".repeat(indent + 2)
  const lines = Object.entries(colors).map(([group, entries]) => {
    const keys = Object.keys(entries)
    if (keys.length === 1 && keys[0] === "DEFAULT") {
      return `${pad}${key(group)}: "${entries.DEFAULT}",`
    }
    const inner = Object.entries(entries)
      .map(([k, v]) => `${pad}  ${key(k)}: "${v}",`)
      .join("\n")
    return `${pad}${key(group)}: {\n${inner}\n${pad}},`
  })
  return `{\n${lines.join("\n")}\n${" ".repeat(indent)}}`
}

function formatFontFamily(families: Record<string, string>, indent: number) {
  const pad = " ".repeat(indent + 2)
  const lines = Object.entries(families).map(
    ([name, ref]) => `${pad}${key(name)}: ["${ref}"],`
  )
  return `{\n${lines.join("\n")}\n${" ".repeat(indent)}}`
}

function formatFontSize(sizes: FontSizes, indent: number) {
  const pad = " ".repeat(indent + 2)
  const lines = Object.entries(sizes).map(([name, [size, options]]) => {
    const opts = Object.entries(options)
      .map(([k, v]) => `${k}: "${v}"`)
      .join(", ")
    return opts
      ? `${pad}${key(name)}: ["${size}", { ${opts} }],`
      : `${pad}${key(name)}: "${size}",`
  })
  return `{\n${lines.join("\n")}\n${" ".repeat(indent)}}`
}

function formatStrings(entries: Record<string, string>, indent: number) {
  const pad = " ".repeat(indent + 2)
  const lines = Object.entries(entries).map(
    ([name, value]) => `${pad}${key(name)}: "${value}",`
  )
  return `{\n${lines.join("\n")}\n${" ".repeat(indent)}}`
}
