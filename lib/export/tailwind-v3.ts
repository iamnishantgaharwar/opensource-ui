import { cssGroups, hslChannels, type ExportFile } from "@/lib/export/shared"
import type { TokenGroup } from "@/lib/tokens/types"

type ColorTree = Record<string, Record<string, string>>

/**
 * Tailwind v3 in shadcn's v3 style: HSL channel variables in globals.css and
 * a config that wraps them in `hsl(var(--x))`. Names split on the first dash:
 * `primary-500` → colors.primary.500, `primary` → colors.primary.DEFAULT.
 */
export function exportTailwindV3(tree: TokenGroup): ExportFile[] {
  const root: string[] = []
  const dark: string[] = []
  const colors: ColorTree = {}

  for (const { label, leaves } of cssGroups(tree)) {
    const colorLeaves = leaves.filter((l) => l.token.$type === "color")
    if (!colorLeaves.length) continue
    root.push(`    /* ${label} */`)
    const darkLines: string[] = []
    for (const { token } of colorLeaves) {
      const name = token.$css!
      root.push(`    --${name}: ${hslChannels(String(token.$value))};`)
      if (token.$dark !== undefined) {
        darkLines.push(`    --${name}: ${hslChannels(String(token.$dark))};`)
      }
      const [group, ...rest] = name.split("-")
      colors[group] ??= {}
      colors[group][rest.length ? rest.join("-") : "DEFAULT"] =
        `hsl(var(--${name}))`
    }
    if (darkLines.length) dark.push(`    /* ${label} */`, ...darkLines)
  }

  const css = [
    "/* Generated by opensource-ui. Replace your :root and .dark blocks. */",
    "@layer base {",
    "  :root {",
    ...root,
    "  }",
    "",
    "  .dark {",
    ...dark,
    "  }",
    "}",
    "",
  ].join("\n")

  const config = [
    "/** @type {import('tailwindcss').Config} */",
    "module.exports = {",
    '  darkMode: ["class"],',
    "  theme: {",
    "    extend: {",
    `      colors: ${formatColors(colors, 6)},`,
    "    },",
    "  },",
    "}",
    "",
  ].join("\n")

  return [
    { filename: "globals.css", language: "css", code: css },
    { filename: "tailwind.config.js", language: "js", code: config },
  ]
}

const key = (k: string) =>
  /^([a-z_]\w*|\d+)$/i.test(k) ? k : JSON.stringify(k)

function formatColors(colors: ColorTree, indent: number) {
  const pad = " ".repeat(indent + 2)
  const lines = Object.entries(colors).map(([group, entries]) => {
    const keys = Object.keys(entries)
    if (keys.length === 1 && keys[0] === "DEFAULT") {
      return `${pad}${key(group)}: "${entries.DEFAULT}",`
    }
    const inner = Object.entries(entries)
      .map(([k, v]) => `${pad}  ${key(k)}: "${v}",`)
      .join("\n")
    return `${pad}${key(group)}: {\n${inner}\n${pad}},`
  })
  return `{\n${lines.join("\n")}\n${" ".repeat(indent)}}`
}
